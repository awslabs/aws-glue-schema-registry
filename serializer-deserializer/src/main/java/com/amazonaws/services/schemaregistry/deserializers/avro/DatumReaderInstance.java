package com.amazonaws.services.schemaregistry.deserializers.avro;

import com.amazonaws.services.schemaregistry.utils.AVROUtils;
import com.amazonaws.services.schemaregistry.utils.AvroRecordType;
import lombok.extern.slf4j.Slf4j;
import org.apache.avro.Schema;
import org.apache.avro.generic.GenericDatumReader;
import org.apache.avro.io.DatumReader;
import org.apache.avro.specific.SpecificData;
import org.apache.avro.specific.SpecificDatumReader;
import org.apache.avro.specific.SpecificRecord;

@Slf4j
public class DatumReaderInstance {
    private static final AVROUtils AVRO_UTILS = AVROUtils.getInstance();

    /**
     * This method is used to create Avro datum reader for deserialization. By
     * default, it is GenericDatumReader; SpecificDatumReader will only be created
     * if the user specifies. In this case, the program will check if the user have
     * those specific code-generated schema class locally. ReaderSchema will be
     * supplied if the user wants to use a specific schema to deserialize the
     * message. (Compatibility check will be invoked)
     *
     * @param writerSchemaDefinition Avro record writer schema.
     * @return Avro datum reader for de-serialization
     * @throws InstantiationException can be thrown for readerClass.newInstance()
     *                                from java.lang.Class implementation
     * @throws IllegalAccessException can be thrown readerClass.newInstance() from
     *                                java.lang.Class implementation
     */
    public static DatumReader<Object> from(String writerSchemaDefinition, AvroRecordType avroRecordType)
        throws InstantiationException, IllegalAccessException {

        Schema writerSchema = AVRO_UTILS.parseSchema(writerSchemaDefinition);

        switch (avroRecordType) {
            case SPECIFIC_RECORD:
                Class<SpecificRecord> readerClass = resolveSpecificRecordClass(writerSchema);

                Schema readerSchema = readerClass.newInstance().getSchema();
                log.debug("Using SpecificDatumReader for de-serializing Avro message, schema: {})",
                    readerSchema.toString());
                return new SpecificDatumReader<>(writerSchema, readerSchema);

            case GENERIC_RECORD:
                log.debug("Using GenericDatumReader for de-serializing Avro message, schema: {})",
                    writerSchema.toString());
                return new GenericDatumReader<>(writerSchema);

            default:
                String message = String.format("Unsupported AvroRecordType: %s",
                    avroRecordType.getName());
                throw new UnsupportedOperationException(message);
        }
    }

    /**
     * Resolves the generated reader class named by {@code writerSchema}, checking it before it is
     * initialized or constructed.
     * <p>
     * The class name comes from the writer schema's namespace and name, which is registry content
     * rather than application configuration, so a schema author selects which class is resolved.
     * {@code SpecificData.getClass(Schema)} loads and initializes it, and the caller's
     * {@code newInstance()} then also runs its no-argument constructor, with the
     * {@code ClassCastException} for a non-record arriving only afterwards. Both have already had
     * their effect by then, so the name is resolved here with {@code initialize=false} and the
     * class rejected before either can happen.
     *
     * @param writerSchema parsed writer schema
     * @return the reader class, guaranteed to be a {@link SpecificRecord}
     * @throws IllegalArgumentException if the named class is absent from the classpath or is not a
     *                                  {@link SpecificRecord}
     */
    private static Class<SpecificRecord> resolveSpecificRecordClass(Schema writerSchema) {
        final String readerClassName = SpecificData.getClassName(writerSchema);

        final Class<?> candidate;
        try {
            // SpecificData's own loader, so this resolves the same class its getClass() would.
            candidate = Class.forName(readerClassName, false, SpecificData.get().getClassLoader());
        } catch (ClassNotFoundException e) {
            throw new IllegalArgumentException(String.format(
                "Avro schema resolves to class %s, which is not on the classpath.", readerClassName), e);
        }

        // Every class this path is meant to reach is generated by the Avro compiler and so
        // implements SpecificRecord. Requiring it keeps a schema from naming an unrelated class,
        // without the consumer having to configure anything.
        if (!SpecificRecord.class.isAssignableFrom(candidate)) {
            throw new IllegalArgumentException(String.format(
                "Avro schema resolves to class %s, which is not a %s.",
                readerClassName, SpecificRecord.class.getName()));
        }

        @SuppressWarnings("unchecked")
        Class<SpecificRecord> readerClass = (Class<SpecificRecord>) candidate;
        return readerClass;
    }
}
